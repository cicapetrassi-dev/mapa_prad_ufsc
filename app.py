with aba_guia:
    st.markdown("## 🌱 Você Conhece o PRAD/UFSC?")
    st.markdown(
        "Síntese do **Guia Educativo PRAD/UFSC** (Sala Verde / Departamento de"
        " Gestão Ambiental — Campus Florianópolis, 2026)."
    )

    with st.expander("📌 O que é o PRAD/UFSC e por que recuperar essas áreas?", expanded=True):
        st.markdown(
            """
            - **O que é:** O Projeto de Recuperação de Áreas Degradadas da UFSC (**PRAD/UFSC**) foi elaborado para a unidade Trindade (Campus Florianópolis), com o objetivo geral de contribuir para melhorar a qualidade da água superficial dos cursos d'água que atravessam o campus.
            - **Origem:** Elaborado em atendimento a uma decisão judicial relacionada à canalização e ao aterramento de um curso d'água no campus, buscando reparar danos ambientais e orientar ações de recuperação sob responsabilidade da Universidade.
            - **Por que recuperar:**
              1. **Proteger os recursos hídricos:** os córregos do campus integram a bacia hidrográfica do Rio do Meio, seguindo em direção ao manguezal do Itacorubi.
              2. **Proteger o solo e as margens:** a vegetação ajuda a reduzir a erosão e conservar as margens.
              3. **Favorecer a biodiversidade:** áreas vegetadas oferecem abrigo e alimento para a fauna.
              4. **Preservar as APPs:** proteger Áreas de Preservação Permanente contribui para conservar os ecossistemas.
              5. **Recuperar áreas degradadas:** ações de proteção e recuperação em trechos prioritários.
              6. **Acompanhar os resultados:** a recuperação é gradual e exige cuidados e monitoramento contínuos.
            """
        )

    with st.expander("🧩 Quatro eixos que trabalham juntos", expanded=True):
        st.markdown(
            """
            1. **Recuperação das margens e compensação ambiental:** proteção de APPs, cercamento e sinalização, recomposição da vegetação nativa e ações para recuperação das margens e compensação de ocupações.
            2. **Qualidade da água:** análises e monitoramento dos cursos d'água para acompanhar condições e mudanças ao longo do tempo.
            3. **Esgotamento sanitário:** inspeções, identificação de inconformidades e adequação das ligações sanitárias, com atenção aos impactos potenciais sobre os córregos.
            4. **Educação ambiental:** atividades educativas, materiais informativos, vivências em campo e participação para aproximar a comunidade do projeto.
            """
        )

    with st.expander("🎬 Animação: Caminho dos Efluentes e Mata Ciliar", expanded=True):
        st.markdown(
            """
            A adequação do esgotamento sanitário e a recomposição da vegetação nas margens (mata ciliar) trabalham juntas para evitar que efluentes cheguem aos córregos e para proteger os cursos d'água da bacia do Rio do Meio.

            Assista à animação do **PRAD/UFSC** (*Percurso Adequado dos Efluentes e Importância da Mata Ciliar na Recuperação Ambiental - PRAD/UFSC*):
            👉 [Assistir no YouTube](https://www.youtube.com/watch?v=2hNqt5yLcjI)
            """
        )

    with st.expander("🚀 O que avançou em 2025 (Ano 1 de execução)"):
        st.markdown(
            """
            - **Recuperação e compensação ambiental:** plantio de mais de 500 mudas nativas em quatro áreas do campus, implantação inicial de cercamentos e sinalização de APPs e demolição das bases das antigas edificações CCB17 e CCB18.
            - **Qualidade da água:** definição de 35 pontos de monitoramento e planejamento de quatro campanhas anuais, com retomada da contratação das análises após liberação de recursos em outubro.
            - **Esgotamento sanitário:** diagnóstico de edificações críticas, elaboração de projetos de adequação na Moradia Estudantil e implantação da rede de esgoto do Setor 01 da Prefeitura Universitária.
            - **Educação ambiental:** realização de sete atividades educativas, incluindo visitas guiadas, mutirões de plantio e divulgação de materiais educativos.
            """
        )

    with st.expander("🤝 Como você pode contribuir?"):
        st.markdown(
            """
            - Respeite as áreas sinalizadas e os locais em recuperação.
            - Não retire mudas, plantas ou materiais de proteção das áreas.
            - Não descarte lixo, bitucas de cigarro ou qualquer material na vegetação e nas margens dos córregos.
            - Evite pisotear áreas plantadas e siga as orientações durante visitas e atividades de campo.
            - Participe das atividades educativas e compartilhe informações sobre o PRAD.
            - Comunique situações de risco, poluição ou danos às áreas aos setores responsáveis.
            """
        )

